"""Markdown exporter."""

from pathlib import Path
from typing import Union
from datetime import datetime

from .base import Exporter
from ...core.types import SessionResult, TaskStatus


class MarkdownExporter(Exporter):
    """Export results to Markdown format."""
    
    name = "markdown"
    extension = ".md"
    description = "Markdown format"
    
    def export(
        self,
        session: SessionResult,
        output_path: Union[str, Path]
    ) -> Path:
        """Export to Markdown file."""
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        
        content = self.export_string(session)
        
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        
        return path
    
    def export_string(self, session: SessionResult) -> str:
        """Export to Markdown string."""
        lines = []
        
        # Header
        lines.append(f"# {session.sequence_name}")
        lines.append("")
        
        # Session info
        lines.append("## Session Information")
        lines.append("")
        lines.append(f"- **Session ID:** {session.session_id}")
        lines.append(f"- **Started:** {self._format_datetime(session.started_at)}")
        
        if session.completed_at:
            lines.append(f"- **Completed:** {self._format_datetime(session.completed_at)}")
            lines.append(f"- **Duration:** {self._format_duration(session.duration_seconds)}")
        
        lines.append(f"- **Total Tasks:** {session.total_tasks}")
        lines.append(f"- **Completed:** {session.completed_tasks}")
        lines.append(f"- **Failed:** {session.failed_tasks}")
        lines.append("")
        
        # Summary
        if session.total_tasks > 0:
            success_rate = (session.completed_tasks / session.total_tasks) * 100
            lines.append(f"**Success Rate:** {success_rate:.1f}%")
            lines.append("")
        
        # Results
        lines.append("## Results")
        lines.append("")
        
        for i, result in enumerate(session.results, 1):
            status_emoji = self._get_status_emoji(result.status)
            
            lines.append(f"### {i}. {result.task_name} {status_emoji}")
            lines.append("")
            
            # Prompt
            lines.append("**Prompt:**")
            lines.append("")
            lines.append("```")
            lines.append(result.prompt)
            lines.append("```")
            lines.append("")
            
            # Response
            if result.response:
                lines.append("**Response:**")
                lines.append("")
                # Escape any markdown in response
                lines.append(result.response)
                lines.append("")
            
            # Error
            if result.error_message:
                lines.append(f"**Error:** `{result.error_message}`")
                lines.append("")
            
            # Metadata
            lines.append(f"*Status: {result.status.name} | Duration: {result.duration_seconds:.1f}s*")
            lines.append("")
            lines.append("---")
            lines.append("")
        
        # Footer
        lines.append("")
        lines.append(f"*Generated by ChatFlow Automator*")
        
        return "\n".join(lines)
    
    def _format_datetime(self, dt: datetime) -> str:
        """Format datetime for display."""
        return dt.strftime("%Y-%m-%d %H:%M:%S")
    
    def _format_duration(self, seconds: float) -> str:
        """Format duration for display."""
        if seconds < 60:
            return f"{seconds:.1f} seconds"
        elif seconds < 3600:
            minutes = seconds / 60
            return f"{minutes:.1f} minutes"
        else:
            hours = seconds / 3600
            return f"{hours:.1f} hours"
    
    def _get_status_emoji(self, status: TaskStatus) -> str:
        """Get emoji for status."""
        emoji_map = {
            TaskStatus.COMPLETED: "✅",
            TaskStatus.FAILED: "❌",
            TaskStatus.CANCELLED: "⚪",
            TaskStatus.RUNNING: "🔄",
            TaskStatus.WAITING_RESPONSE: "⏳",
            TaskStatus.PAUSED: "⏸️",
            TaskStatus.PENDING: "⏺️",
        }
        return emoji_map.get(status, "❓")
